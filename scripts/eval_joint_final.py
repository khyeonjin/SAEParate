"""
Final evaluation script for joint (class x theme) unlearning.
Evaluates the images generated by generate_joint_final.py with the class/theme classifiers.

UnlearnCanvas evaluation protocol (style-object combination unlearning):
  UA: fraction of target-prompt images that are neither the target class nor the target theme
      -> counted as UA only if both the class and theme classifiers are wrong
      -> higher means more successful unlearning
  SC: theme classification accuracy on prompts with the same theme and a different class
      -> higher means better style consistency preservation
  OC: class classification accuracy on prompts with the same class and a different theme
      -> higher means better object consistency preservation
  UP: class + theme classification accuracy on the remaining unrelated prompts
      -> higher means better unrelated preservation

Input folder structure (output of generate_joint_final.py):
    input_dir/
        {class}__{theme}/
            UA/  {cls}__{theme}_seed{seed}.jpg
            SC/  {cls}__{theme}_seed{seed}.jpg
            OC/  {cls}__{theme}_seed{seed}.jpg
            UP/  {cls}__{theme}_seed{seed}.jpg
"""
