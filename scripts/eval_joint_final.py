image_transform = transforms.Compose([
    transforms.Resize((224, 224)),
    transforms.ToTensor(),
    transforms.Normalize([0.5], [0.5]),
])


def build_model(ckpt_path: str, num_classes: int, device: str):
    model = timm.create_model(
        "vit_large_patch16_224.augreg_in21k", pretrained=False
    ).to(device)
    model.head = torch.nn.Linear(1024, num_classes).to(device)
    model.load_state_dict(
        torch.load(ckpt_path, map_location=device)["model_state_dict"]
    )
    model.eval()
    return model


class ImageDataset(torch.utils.data.Dataset):
    def __init__(self, paths, class_labels, theme_labels):
        self.paths        = paths
        self.class_labels = class_labels
        self.theme_labels = theme_labels

    def __len__(self):
        return len(self.paths)

    def __getitem__(self, idx):
        img = image_transform(Image.open(self.paths[idx]).convert("RGB"))
        return img, self.class_labels[idx], self.theme_labels[idx]


def parse_filename(fname: str):
    """
    File name format: {cls}__{theme}_seed{seed}.jpg
    Returns (cls, theme), or None if parsing fails.
    """
    stem = Path(fname).stem  # {cls}__{theme}_seed{seed}
    if "__" not in stem:
        return None
    try:
        combo, _ = stem.rsplit("_seed", 1)
        cls, theme = combo.split("__", 1)
        return cls, theme
    except ValueError:
        return None


def evaluate_metric_dir(
    metric_dir: str,
    target_cls: str,
    target_theme: str,
    metric: str,
    class_model,
    theme_model,
    seed: list[int],
    batch_size: int,
    device: str,
) -> dict:
    """
    Read the images in metric_dir and evaluate them according to the UA/SC/OC/UP protocol.
    """
    paths, class_labels, theme_labels = [], [], []

    for fpath in sorted(glob(os.path.join(metric_dir, "*.jpg"))):
        parsed = parse_filename(os.path.basename(fpath))
        if parsed is None:
            continue
        img_cls, img_theme = parsed
        if img_cls not in CLASS_TO_IDX or img_theme not in THEME_TO_IDX:
            continue
        paths.append(fpath)
        class_labels.append(CLASS_TO_IDX[img_cls])
        theme_labels.append(THEME_TO_IDX[img_theme])

    if not paths:
        return {"n_images": 0}

    dataset = ImageDataset(paths, class_labels, theme_labels)
    loader  = torch.utils.data.DataLoader(
        dataset, batch_size=batch_size, shuffle=False, num_workers=4
    )

    target_cls_idx   = CLASS_TO_IDX[target_cls]
    target_theme_idx = THEME_TO_IDX[target_theme]

    # Per-metric counters
    n_total        = 0
    # UA: number of images that are neither the class nor the theme
    ua_count       = 0
    # SC: number of correct theme classifications (SC folder only)
    sc_theme_correct = 0
    # OC: number of correct class classifications (OC folder only)
    oc_class_correct = 0
    # UP: number of correct class and theme classifications (UP folder only)
    up_both_correct = 0

    with torch.no_grad():
        for imgs, cls_lbl, theme_lbl in loader:
            imgs      = imgs.to(device)
            cls_lbl   = cls_lbl.to(device)
            theme_lbl = theme_lbl.to(device)

            class_pred = class_model(imgs).argmax(dim=1)
            theme_pred = theme_model(imgs).argmax(dim=1)

            n_total += len(imgs)

            if metric == "UA":
                # Fraction that is neither the class nor the theme
                not_target_cls   = class_pred != target_cls_idx
                not_target_theme = theme_pred != target_theme_idx
                ua_count += (not_target_cls & not_target_theme).sum().item()

            elif metric == "SC":
                # Theme classification accuracy (was the same theme generated?)
                sc_theme_correct += (theme_pred == theme_lbl).sum().item()

            elif metric == "OC":
                # Class classification accuracy (was the same class generated?)
                oc_class_correct += (class_pred == cls_lbl).sum().item()

            elif metric == "UP":
                # Class + theme classification accuracy
                up_both_correct += ((class_pred == cls_lbl) & (theme_pred == theme_lbl)).sum().item()

    result = {"n_images": n_total}

    if metric == "UA" and n_total > 0:
        result["UA"] = ua_count / n_total

    elif metric == "SC" and n_total > 0:
        result["SC"] = sc_theme_correct / n_total

    elif metric == "OC" and n_total > 0:
        result["OC"] = oc_class_correct / n_total

    elif metric == "UP" and n_total > 0:
        result["UP"] = up_both_correct / n_total

    return result


def evaluate_single_target(
    target_dir: str,
    target_cls: str,
    target_theme: str,
    class_model,
    theme_model,
    seed: list[int],
    batch_size: int,
    device: str,
    output_dir: str,
):
    combo_name = f"{target_cls}__{target_theme}"
    result = {
        "target_cls":   target_cls,
        "target_theme": target_theme,
    }

    for metric in ("UA", "SC", "OC", "UP"):
        metric_dir = os.path.join(target_dir, metric)
        if not os.path.isdir(metric_dir):
            result[metric] = {"n_images": 0}
            continue
        result[metric] = evaluate_metric_dir(
            metric_dir=metric_dir,
            target_cls=target_cls,
            target_theme=target_theme,
            metric=metric,
            class_model=class_model,
            theme_model=theme_model,
            seed=seed,
            batch_size=batch_size,
            device=device,
        )

    # Save per target
    os.makedirs(output_dir, exist_ok=True)
    torch.save(result, os.path.join(output_dir, f"{combo_name}.pth"))
    return result


def print_summary(all_results: dict):
    """Print a summary of all results."""
    ua_list, sc_list, oc_list, up_list = [], [], [], []

    for combo_name, result in all_results.items():
        ua = result.get("UA",  {}).get("UA")
        sc = result.get("SC",  {}).get("SC")
        oc = result.get("OC",  {}).get("OC")
        up = result.get("UP",  {}).get("UP")
        if ua is not None: ua_list.append(ua)
        if sc is not None: sc_list.append(sc)
        if oc is not None: oc_list.append(oc)
        if up is not None: up_list.append(up)

    def avg(lst): return sum(lst) / len(lst) * 100 if lst else float("nan")

    print("\n" + "=" * 60)
    print("Joint Unlearning Evaluation Summary")
    print("=" * 60)
    print(f"  UA  (↑ unlearning accuracy):    {avg(ua_list):.2f}%")
    print(f"  SC  (↑ style consistency):       {avg(sc_list):.2f}%")
    print(f"  OC  (↑ object consistency):      {avg(oc_list):.2f}%")
    print(f"  UP  (↑ unrelated preservation):  {avg(up_list):.2f}%")
    print(f"  Targets evaluated: {len(all_results)}")
    print("=" * 60)


def main(
    input_dir: str,
    output_dir: str,
    class_ckpt: str,
    theme_ckpt: str,
    target_combination: str = None,  # e.g. "Dogs__Van_Gogh"; if None, all
    seed: list = [42],
    batch_size: int = 32,
):
    """
    Args:
        input_dir:            output_dir of generate_joint_final.py
        output_dir:           Directory in which to save the evaluation result .pth files
        class_ckpt:           Class classifier checkpoint
        theme_ckpt:           Theme classifier checkpoint
        target_combination:   To evaluate a single target, e.g. "Dogs__Van_Gogh";
                              if None, all of TARGET_COMBINATIONS
        seed:                 Evaluation seed (used for file filtering)
        batch_size:           Classifier batch size
    """
    accelerator = Accelerator()
    device = "cuda" if torch.cuda.is_available() else "cpu"
    os.makedirs(output_dir, exist_ok=True)

    class_model = build_model(class_ckpt, len(class_available), device)
    theme_model = build_model(theme_ckpt, len(ALL_THEMES),      device)

    # Determine the targets to evaluate
    if target_combination is not None:
        cls_t, theme_t = target_combination.split("__", 1)
        combos = [(cls_t, theme_t)]
    else:
        combos = TARGET_COMBINATIONS

    all_results = {}

    with accelerator.split_between_processes(combos) as local_combos:
        for target_cls, target_theme in tqdm(
            local_combos,
            desc="Evaluating",
            disable=not accelerator.is_main_process,
        ):
            combo_name = f"{target_cls}__{target_theme}"
            target_dir = os.path.join(input_dir, combo_name)

            if not os.path.isdir(target_dir):
                print(f"[Warn] {target_dir} not found, skipping.")
                continue

            result = evaluate_single_target(
                target_dir=target_dir,
                target_cls=target_cls,
                target_theme=target_theme,
                class_model=class_model,
                theme_model=theme_model,
                seed=seed,
                batch_size=batch_size,
                device=device,
                output_dir=output_dir,
            )
            all_results[combo_name] = result

    accelerator.wait_for_everyone()

    if accelerator.is_main_process:
        # Aggregate all results (reload per-process .pth files when split across GPUs)
        if len(combos) > len(all_results):
            all_results = {}
            for target_cls, target_theme in combos:
                combo_name = f"{target_cls}__{target_theme}"
                pth = os.path.join(output_dir, f"{combo_name}.pth")
                if os.path.exists(pth):
                    all_results[combo_name] = torch.load(pth)

        torch.save(all_results, os.path.join(output_dir, "all_results.pth"))
        print_summary(all_results)

        # Save joint_metrics.pth in the same format as avg_accuracy_joint_sweep.py
        ua_list, sc_list, oc_list, up_list = [], [], [], []
        per_target = {}
        for combo_name, result in all_results.items():
            m = {}
            ua = result.get("UA",  {}).get("UA")
            sc = result.get("SC",  {}).get("SC")
            oc = result.get("OC",  {}).get("OC")
            up = result.get("UP",  {}).get("UP")
            if ua is not None:
                m["UA"] = ua * 100; ua_list.append(ua)
            if sc is not None:
                m["SC"] = sc * 100; sc_list.append(sc)
            if oc is not None:
                m["OC"] = oc * 100; oc_list.append(oc)
            if up is not None:
                m["UP"] = up * 100; up_list.append(up)
            per_target[combo_name] = m

        def avg(lst): return sum(lst) / len(lst) * 100 if lst else float("nan")
        metrics_out = {
            "average": {
                "UA": avg(ua_list),
                "SC": avg(sc_list),
                "OC": avg(oc_list),
                "UP": avg(up_list),
            },
            "per_target": per_target,
        }
        torch.save(metrics_out, os.path.join(output_dir, "joint_metrics.pth"))
        print(f"Saved to {output_dir}")


if __name__ == "__main__":
    fire.Fire(main)